/**
 * A46: приведение объекта к «словарю» для API.
 *
 * Раньше в пяти местах стояло `value as unknown as Record<string, unknown>` —
 * двойное приведение **отключает проверку типов целиком**: если форма объекта
 * разойдётся с ожидаемой, компилятор промолчит, а ошибка вылезет в рантайме
 * (`undefined` вместо данных).
 *
 * Здесь данные не переинтерпретируются: объект поверхностно копируется, а
 * приведение стоит на пустом литерале. Единственное, что теряется, —
 * прототип, и для JSON-пейлоада это и нужно.
 */
export function toPayload(value: object): Record<string, unknown> {
  return Object.assign({} as Record<string, unknown>, value);
}
