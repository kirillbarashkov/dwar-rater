/**
 * A43: единственный список рангов игры.
 *
 * До этого в проекте жили **три** копии: массив из 15 значений в
 * `ClanMembersTable` (выпадающий список «Добавить участника») и две одинаковые
 * карты «уровень → ранг» из 20 значений (`ClosedProfilesTab`,
 * `ClosedProfileBanner`). Из-за расхождения форма добавления не предлагала
 * ранги «Рекрут», «Солдат», «Боец», «Воин», «Победоносец» — участника с таким
 * рангом нельзя было завести, хотя в остальном приложении он отображался.
 *
 * Карта — источник истины (это лестница игры, уровень 1..20). Массив для
 * выпадающих списков выводится из неё в порядке «старший ранг первым».
 */

export const GAME_RANKS_BY_LEVEL: Record<number, string> = {
  1: 'Рекрут',
  2: 'Солдат',
  3: 'Боец',
  4: 'Воин',
  5: 'Элитный воин',
  6: 'Чемпион',
  7: 'Гладиатор',
  8: 'Полководец',
  9: 'Мастер войны',
  10: 'Герой',
  11: 'Военный эксперт',
  12: 'Магистр войны',
  13: 'Вершитель',
  14: 'Высший магистр',
  15: 'Повелитель',
  16: 'Легендарный завоеватель',
  17: 'Властелин боя',
  18: 'Победоносец',
  19: 'Триумфатор',
  20: 'Избранник богов',
};

export const GAME_RANKS: string[] = Object.keys(GAME_RANKS_BY_LEVEL)
  .map(Number)
  .sort((a, b) => b - a)
  .map((level) => GAME_RANKS_BY_LEVEL[level]);

export function rankName(level: number | null | undefined): string {
  if (level == null) return '';
  return GAME_RANKS_BY_LEVEL[level] ?? '';
}
